export function msg(key, params = {}) {
  const template = STUDIO_MESSAGES[key];
  if (typeof template !== "string") throw new Error(`STUDIO_MESSAGE_MISSING:${key}`);
  return template.replace(/\{(\w+)\}/gu, (_, name) => String(params[name] ?? ""));
}

// 원문 오류 문자열은 렌더하지 않는다. 안전한 코드만 문구로 바꾼다.
export function studioErrorMessage(code) {
  return typeof code === "string" && /^[A-Z][A-Z0-9_]{2,63}$/u.test(code) && STUDIO_ERRORS[code] ? STUDIO_ERRORS[code] : STUDIO_MESSAGES["studio.error.generic"];
}
